export type ImageKind = keyof typeof PRODUCT_IMAGE_SETS;

/** Resolve the correct dedicated photo set from a product's own attributes. */
export function imageKindFor(name: string, subcategory: string): ImageKind {
  const n = name.toLowerCase();
  switch (subcategory) {
    case "Oversized T-Shirts":
      return "tee-oversized";
    case "Graphic T-Shirts":
      return "tee-graphic";
    case "Heavyweight T-Shirts":
      return "tee-heavy";
    case "Hoodies":
      return "hoodie";
    case "Sweatshirts":
      return "sweatshirt";
    case "Bomber Jackets":
      return "jacket-bomber";
    case "Denim Jackets":
      return "jacket-denim";
    case "Technical Jackets":
      if (n.includes("puffer")) return "puffer";
      if (n.includes("overcoat")) return "overcoat";
      if (n.includes("vest")) return "vest";
      return "jacket-tech";
    case "Denim":
      return "denim";
    case "Cargo Pants":
      return "cargo";
    case "Joggers":
      return "jogger";
    case "Wide-Leg Trousers":
      return "trouser";
    case "Shorts":
      return n.includes("denim") ? "shorts-denim" : "shorts-cargo";
    case "Sneakers":
      if (n.includes("trail") || n.includes("chunky")) return "sneaker-trail";
      if (n.includes("low") || n.includes("court") || n.includes("skate"))
        return "sneaker-low";
      return "sneaker";
    case "Bags":
      return n.includes("duffle") ? "duffle" : "crossbody";
    case "Backpacks":
      return "backpack";
    case "Caps":
      return "cap";
    case "Beanies":
      return "beanie";
    case "Sunglasses":
      return "sunglasses";
    case "Belts":
      return "belt";
    default:
      return "tee-oversized";
  }
}

/** Dedicated images for one product. Never borrows another product's photo. */
export function imagesFor(name: string, subcategory: string): string[] {
  return [...PRODUCT_IMAGE_SETS[imageKindFor(name, subcategory)]];
}